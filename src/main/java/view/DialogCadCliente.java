    private void limparCamposCliente() {
        txtNome.setText("");
        txtCPF.setValue(null);
        txtDtNasc.setValue(null);
        txtTelefone.setValue(null);
        txtCEP.setValue(null);
        limparCamposEndereco();
    }

    private String getComboValue(javax.swing.JComboBox<String> combo) {
        Object selected = combo.getSelectedItem();
        if (selected == null) {
            return "";
        }
        String value = selected.toString().trim();
        if (value.isEmpty() || value.toLowerCase().startsWith("item")) {
            return "";
        }
        return value;
    }

    private List<String> validarCamposCliente(String nome,
            String cpf,
            String telefone,
            LocalDate dtNasc,
            String cep,
            String rua,
            String bairro,
            String cidade,
            String uf) {
        List<String> erros = new ArrayList<>();

        if (nome.isEmpty()) {
            erros.add("Informe o nome.");
        }
        if (cpf.length() != 11) {
            erros.add("Informe um CPF valido.");
        }
        if (dtNasc == null) {
            erros.add("Informe uma data de nascimento valida.");
        }
        if (telefone.length() < 10 || telefone.length() > 11) {
            erros.add("Informe um telefone valido.");
        }
        if (cep.length() != 8) {
            erros.add("Informe um CEP valido.");
        }
        if (rua.isEmpty()) {
            erros.add("Informe a rua.");
        }
        if (bairro.isEmpty()) {
            erros.add("Informe o bairro.");
        }
        if (cidade.isEmpty()) {
            erros.add("Informe a cidade.");
        }
        if (uf.isEmpty()) {
            erros.add("Informe a UF.");
        }

        return erros;
    }

    private LocalDate parseDataNascimento(String rawValue) {
        String normalized = rawValue == null ? "" : rawValue.trim();
        if (onlyDigits(normalized).isEmpty()) {
            return null;
        }
        try {
            return LocalDate.parse(normalized, DATE_FORMATTER);
        } catch (DateTimeParseException ex) {
            return null;
        }
    }

    private String onlyDigits(String value) {
        return value == null ? "" : value.replaceAll("\\D", "");
    }


